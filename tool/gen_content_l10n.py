"""Generate content-catalogue localization from catalogue.json.

Writes the keys into every arb file (English everywhere, per the
translator-placeholder approach) and emits lib/ui/content_l10n.dart with
id-keyed resolvers. Definitions keep their English text, which the
resolvers use as a fallback, so an id we have no key for still renders.
"""
import json
import glob
import re
import sys
import io
from collections import OrderedDict

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8',
                              errors='replace')

cat = json.load(open('tool/catalogue.json', encoding='utf-8'))


def camel(prefix, raw):
    parts = re.split(r'[_\s]+', raw)
    return prefix + ''.join(p[:1].upper() + p[1:] for p in parts if p)


def clean(s):
    """Undo Dart source escaping; arb holds the literal text."""
    return s.replace("\\'", "'").replace('\\"', '"') if s else s


keys = OrderedDict()
resolvers = []


def build(label, prefix, items, with_desc, fn_name, id_doc):
    name_cases, desc_cases = [], []
    for it in items:
        key = camel(prefix, it['id'])
        keys[key] = clean(it['name'])
        name_cases.append((it['id'], key))
        if with_desc and it.get('desc'):
            dkey = key + 'Desc'
            keys[dkey] = clean(it['desc'])
            desc_cases.append((it['id'], dkey))

    def emit(fname, cases, what):
        body = '\n'.join(
            f"    case '{i}':\n      return l10n.{k};" for i, k in cases)
        return (
            f"/// Localized {what} for a {id_doc}.\n"
            f"///\n"
            f"/// [fallback] is the definition's own English text, returned\n"
            f"/// for any id without a key (e.g. content added since the\n"
            f"/// last l10n pass).\n"
            f"String {fname}(\n"
            f"    AppLocalizations l10n, String id, String fallback) {{\n"
            f"  switch (id) {{\n{body}\n  }}\n"
            f"  return fallback;\n}}\n")

    resolvers.append(emit(fn_name, name_cases, 'name'))
    if desc_cases:
        resolvers.append(
            emit(fn_name.replace('Name', 'Description'), desc_cases,
                 'description'))


build('artifacts', 'artifact', cat['artifacts'], True,
      'localizedArtifactName', 'ArtifactDefinition id')
build('achievements', 'achievement', cat['achievements'], True,
      'localizedAchievementName', 'AchievementDefinition id')
build('items', 'item', cat['items'], False,
      'localizedItemName', 'ItemType name')
build('tiles', 'tile', cat['tiles'], False,
      'localizedTileName', 'TileType name')

# ── arb files ────────────────────────────────────────────────────
for path in sorted(glob.glob('lib/l10n/app_*.arb')):
    data = json.load(open(path, encoding='utf-8'),
                     object_pairs_hook=OrderedDict)
    added = 0
    for k, v in keys.items():
        if k not in data:
            data[k] = v
            added += 1
    json.dump(data, open(path, 'w', encoding='utf-8'),
              ensure_ascii=False, indent=2)
    open(path, 'a', encoding='utf-8').write('\n')
    print(f'{path}: +{added}')

# ── resolver ─────────────────────────────────────────────────────
header = '''/// content_l10n.dart
/// GENERATED by tool/gen_content_l10n.py -- do not hand-edit.
///
/// Maps content-catalogue ids (artifacts, achievements, items, tiles)
/// to their localized names and descriptions.
///
/// The definitions in lib/game/ keep their English text: those layers
/// have no BuildContext, and the id must stay locale-independent so it
/// can be saved and compared. These resolvers translate at render time
/// and fall back to that English for any unknown id.

import '../l10n/app_localizations.dart';

'''
open('lib/ui/content_l10n.dart', 'w', encoding='utf-8').write(
    header + '\n'.join(resolvers))
print(f'\nlib/ui/content_l10n.dart: {len(resolvers)} resolvers, '
      f'{len(keys)} keys')
